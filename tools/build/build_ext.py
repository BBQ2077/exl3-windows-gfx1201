"""Build native/exllamav3_ext.pyd from app/exllamav3/exllamav3_ext (run through tools/build/build_ext.cmd).

1. Mirror app/exllamav3 into build/src/exllamav3 (only files whose bytes differ are copied, so ninja rebuilds
   only what changed) and put tools/build/setup.py next to it.
2. Delete the hipify outputs of every source copied in step 1. torch's hipify never rewrites an existing
   X.hip / X_hip.cuh ("[skipped, already hipified]"), so without this an edited .cu would be compiled from
   its stale .hip.
3. python setup.py build_ext --inplace in build/src.
4. Copy the new exllamav3_ext.*.pyd to native/exllamav3_ext.pyd (the previous one is kept as
   native/exllamav3_ext.pyd.prev) and record its SHA-256 in provenance.json.

Options: --clean  delete build/src first (full rebuild); --no-install  stop after step 3.
"""
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "app" / "exllamav3"
SRC = ROOT / "build" / "src"
NATIVE = ROOT / "native" / "exllamav3_ext.pyd"
HIP_BREADCRUMB = "!!! This is a file automatically generated by hipify!!!"
SOURCE_SUFFIXES = {".cu", ".cuh", ".cpp", ".h", ".hpp", ".c", ".cc"}


def is_hipify_output(path):
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            return HIP_BREADCRUMB in f.read(200)
    except OSError:
        return False


def hip_outputs(src):
    """Files hipify may have generated from src (pytorch-extension naming)."""
    if src.suffix == ".cu":
        yield src.with_suffix(".hip")
    yield src.with_name(f"{src.stem}_hip{src.suffix}")


def sync():
    changed = []
    for p in sorted(APP.rglob("*")):
        rel = p.relative_to(APP)
        if not p.is_file() or "__pycache__" in rel.parts or p.suffix == ".pyc":
            continue
        dst = SRC / "exllamav3" / rel
        if dst.is_file() and dst.read_bytes() == p.read_bytes():
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, dst)
        changed.append(dst)
    setup = Path(__file__).with_name("setup.py")
    if not (SRC / "setup.py").is_file() or (SRC / "setup.py").read_bytes() != setup.read_bytes():
        shutil.copy2(setup, SRC / "setup.py")
    stale = 0
    for dst in changed:
        if dst.suffix in SOURCE_SUFFIXES:
            for out in hip_outputs(dst):
                if out.is_file() and is_hipify_output(out):
                    out.unlink()
                    stale += 1
    print(f"[build] synced {len(changed)} changed file(s) from app/exllamav3, removed {stale} stale hipify output(s)",
          flush=True)


def sha256(p):
    with p.open("rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def main():
    args = set(sys.argv[1:])
    if "--clean" in args and SRC.exists():
        print(f"[build] --clean: removing {SRC}", flush=True)
        shutil.rmtree(SRC)
    SRC.mkdir(parents=True, exist_ok=True)
    sync()
    for old in SRC.glob("exllamav3_ext*.pyd"):
        old.unlink()
    rc = subprocess.call([sys.executable, "setup.py", "build_ext", "--inplace"], cwd=SRC)
    built = sorted(SRC.glob("exllamav3_ext*.pyd"))
    if rc != 0 or not built:
        print(f"[build] FAILED (exit {rc}); native/ left unchanged", flush=True)
        return rc or 1
    pyd = built[-1]
    print(f"[build] built {pyd.name} ({pyd.stat().st_size} bytes)", flush=True)
    if "--no-install" in args:
        return 0
    if NATIVE.is_file():
        shutil.copy2(NATIVE, NATIVE.with_name(NATIVE.name + ".prev"))
    shutil.copy2(pyd, NATIVE)
    digest = sha256(NATIVE)
    prov = ROOT / "provenance.json"
    if prov.is_file():
        data = json.loads(prov.read_text(encoding="utf-8"))
        data.setdefault("native_extensions", {})["exllamav3_ext.pyd"] = digest
        prov.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[build] installed native/exllamav3_ext.pyd sha256={digest}", flush=True)
    print("BUILD_OK", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
